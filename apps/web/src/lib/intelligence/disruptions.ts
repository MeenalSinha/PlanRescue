import type { Disruption, ScheduleEvent, Task } from '../contract';

export interface UrgentTaskAddedDisruption {
  type: 'urgent_task_added';
  taskId: string;
  title: string;
  durationMinutes: number;
  priority: 'critical' | 'high' | 'medium' | 'low';
  dueTime?: string;
}

export interface TimeWindowUnavailableDisruption {
  type: 'time_window_unavailable';
  reason: string;
  startTime: string;
  endTime: string;
}

export type ExpandedDisruption =
  | Disruption
  | UrgentTaskAddedDisruption
  | TimeWindowUnavailableDisruption;

/**
 * Transforms an expanded disruption into an in-memory schedule scenario that the
 * deterministic recovery engine can consume without altering stored database tables.
 */
export function prepareScenarioForExpandedDisruption(
  disruption: ExpandedDisruption,
  events: readonly ScheduleEvent[],
  tasks: readonly Task[],
): {
  effectiveEvents: ScheduleEvent[];
  effectiveTasks: Task[];
  standardDisruption?: Disruption;
  additionalProtectedIds: string[];
} {
  if (disruption.type === 'event_overrun') {
    return {
      effectiveEvents: [...events],
      effectiveTasks: [...tasks],
      standardDisruption: disruption,
      additionalProtectedIds: [],
    };
  }

  if (disruption.type === 'time_window_unavailable') {
    const startMs = Date.parse(disruption.startTime);
    const endMs = Date.parse(disruption.endTime);
    const durationMinutes = Math.max(1, Math.round((endMs - startMs) / 60000));

    // Synthesize an immovable blocking event spanning the unavailable window
    const blockingEvent: ScheduleEvent = {
      id: `synth_block_${Date.now()}`,
      title: `Unavailable: ${disruption.reason}`,
      startTime: disruption.startTime,
      endTime: disruption.endTime,
      durationMinutes,
      priority: 'critical',
      movable: false,
      category: 'focus',
      notes: 'Generated by time_window_unavailable disruption scenario',
    };

    return {
      effectiveEvents: [...events, blockingEvent],
      effectiveTasks: [...tasks],
      additionalProtectedIds: [blockingEvent.id],
    };
  }

  if (disruption.type === 'urgent_task_added') {
    const newTask: Task = {
      id: disruption.taskId,
      title: disruption.title,
      deadline: disruption.dueTime || new Date(Date.now() + 8 * 3600 * 1000).toISOString(),
      estimatedDurationMinutes: disruption.durationMinutes,
      priority: disruption.priority,
      status: 'pending',
    };

    return {
      effectiveEvents: [...events],
      effectiveTasks: [...tasks, newTask],
      additionalProtectedIds: [],
    };
  }

  return {
    effectiveEvents: [...events],
    effectiveTasks: [...tasks],
    additionalProtectedIds: [],
  };
}
